// Bundles prisma/migrations/*/migration.sql into a TS module so the built-in
// demo database (used when DATABASE_URL is not set) can create its schema.
import { readdirSync, readFileSync, writeFileSync, statSync } from "node:fs";
import { join } from "node:path";

const dir = "prisma/migrations";
const sql = readdirSync(dir)
  .filter((d) => statSync(join(dir, d)).isDirectory())
  .sort()
  .map((d) => readFileSync(join(dir, d, "migration.sql"), "utf8"))
  .join("\n");
writeFileSync("src/server/demo/migrations.generated.ts", `// Generated by scripts/embed-migrations.mjs. Do not edit.\nexport const MIGRATIONS_SQL = ${JSON.stringify(sql)};\n`);
